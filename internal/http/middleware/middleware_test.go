func TestRecoverProducesProblemJSON(t *testing.T) {
	h := Recover(http.HandlerFunc(func(_ http.ResponseWriter, _ *http.Request) {
		panic("boom")
	}))
	rr := httptest.NewRecorder()
	h.ServeHTTP(rr, httptest.NewRequest("GET", "/x", nil))
	if rr.Code != http.StatusInternalServerError {
		t.Fatalf("want 500, got %d", rr.Code)
	}
	if ct := rr.Header().Get("Content-Type"); !strings.Contains(ct, "problem+json") {
		t.Fatalf("want problem+json, got %q", ct)
	}
}

func TestReqIDPropagation(t *testing.T) {
	h := ReqID(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		w.WriteHeader(204)
	}))
	rr := httptest.NewRecorder()
	req := httptest.NewRequest("GET", "/x", nil)
	req.Header.Set("X-Request-ID", "abc-123")
	h.ServeHTTP(rr, req)
	if got := rr.Header().Get("X-Request-ID"); got != "abc-123" {
		t.Fatalf("want abc-123, got %q", got)
	}
}

func TestReqIDAutoGenerated(t *testing.T) {
	h := ReqID(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) { w.WriteHeader(204) }))
	rr := httptest.NewRecorder()
	h.ServeHTTP(rr, httptest.NewRequest("GET", "/x", nil))
	if got := rr.Header().Get("X-Request-ID"); got == "" || len(got) < 16 {
		t.Fatalf("want non-empty UUID, got %q", got)
	}
}

func TestSecurityHeaders(t *testing.T) {
	h := SecurityHeaders(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) { w.WriteHeader(204) }))
	rr := httptest.NewRecorder()
	h.ServeHTTP(rr, httptest.NewRequest("GET", "/x", nil))
	wanted := []string{
		"Strict-Transport-Security",
		"Content-Security-Policy",
		"Referrer-Policy",
		"X-Content-Type-Options",
		"X-Frame-Options",
		"Permissions-Policy",
		"Cross-Origin-Opener-Policy",
		"Cross-Origin-Resource-Policy",
	}
	for _, w := range wanted {
		if rr.Header().Get(w) == "" {
			t.Errorf("missing header %s", w)
		}
	}
}

func TestPseudonymStable(t *testing.T) {
	a := Pseudonym("alice@example.test")
	b := Pseudonym("alice@example.test")
	if a != b {
		t.Fatalf("non-deterministic pseudonym: %s vs %s", a, b)
	}
	if Pseudonym("") != "anon" {
		t.Fatal("empty email should pseudonymize to 'anon'")
	}
}
